/// The glyph of a character, if the font has one.
pub fn glyph(c: char) -> Option<&'static [u8; 7]> {
    let c = c.to_ascii_uppercase();
    (' '..='_')
        .contains(&c)
        .then(|| &GLYPHS[c as usize - ' ' as usize])
}
