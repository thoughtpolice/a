// Command lock pins the module proxy files a Go command builds from, as the
// Starlark dictionary in a lock file such as gopls.bzl.
//
// It downloads the command's module zip, reads the go.sum inside it, and
// downloads every go.mod and module zip that go.sum lists, recording the
// sha256 of each so Buck can fetch them as ordinary pinned files. The go
// command still checks each against go.sum when it builds.
//
// Usage:
//
//	lock -module path@version -name NAME [-w FILE]
package main

import (
	"archive/zip"
	"bufio"
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"flag"
	"fmt"
	"io"
	"net/http"
	"os"
	"slices"
	"strings"
	"sync"
)

const proxy = "https://proxy.golang.org"

// A file is one module proxy download: a module's go.mod or its zip.
type file struct {
	path, version, ext string
}

func (f file) url() string {
	return fmt.Sprintf("%s/%s/@v/%s.%s", proxy, escape(f.path), escape(f.version), f.ext)
}

func main() {
	module := flag.String("module", "", "the command's module, as path@version")
	name := flag.String("name", "", "the name of the Starlark dictionary to write")
	write := flag.String("w", "", "write the lock file here instead of to stdout")
	flag.Parse()
	path, version, ok := strings.Cut(*module, "@")
	if !ok || *name == "" || flag.NArg() != 0 {
		fatalf("usage: lock -module path@version -name NAME [-w FILE]")
	}

	body, err := fetch(file{path, version, "zip"}.url())
	if err != nil {
		fatalf("%v", err)
	}
	sum, err := goSum(body, path, version)
	if err != nil {
		fatalf("%s: %v", *module, err)
	}
	files, err := sumFiles(sum)
	if err != nil {
		fatalf("%s go.sum: %v", *module, err)
	}
	hashes, err := hashAll(files)
	if err != nil {
		fatalf("%v", err)
	}

	out := render(*name, *module, *write, sha256Hex(body), files, hashes)
	if *write == "" {
		os.Stdout.Write(out)
		return
	}
	if err := os.WriteFile(*write, out, 0o644); err != nil {
		fatalf("%v", err)
	}
}

// goSum returns the go.sum at the root of a module zip.
func goSum(body []byte, path, version string) ([]byte, error) {
	zr, err := zip.NewReader(bytes.NewReader(body), int64(len(body)))
	if err != nil {
		return nil, err
	}
	f, err := zr.Open(path + "@" + version + "/go.sum")
	if err != nil {
		return nil, err
	}
	defer f.Close()
	return io.ReadAll(f)
}

// sumFiles lists the downloads a go.sum names: a go.mod for each
// "path version/go.mod" line and a zip for each "path version" line.
func sumFiles(sum []byte) ([]file, error) {
	var files []file
	scanner := bufio.NewScanner(bytes.NewReader(sum))
	for scanner.Scan() {
		fields := strings.Fields(scanner.Text())
		if len(fields) == 0 {
			continue
		}
		if len(fields) != 3 {
			return nil, fmt.Errorf("malformed line %q", scanner.Text())
		}
		if v, ok := strings.CutSuffix(fields[1], "/go.mod"); ok {
			files = append(files, file{fields[0], v, "mod"})
		} else {
			files = append(files, file{fields[0], fields[1], "zip"})
		}
	}
	slices.SortFunc(files, func(a, b file) int {
		return strings.Compare(a.path+"@"+a.version+"."+a.ext, b.path+"@"+b.version+"."+b.ext)
	})
	return slices.Compact(files), scanner.Err()
}

// hashAll downloads every file, a few at a time, and returns their sha256s.
func hashAll(files []file) (map[file]string, error) {
	var (
		mu     sync.Mutex
		hashes = map[file]string{}
		errs   []error
		wg     sync.WaitGroup
		sem    = make(chan struct{}, 8)
	)
	for _, f := range files {
		wg.Go(func() {
			sem <- struct{}{}
			defer func() { <-sem }()
			body, err := fetch(f.url())
			mu.Lock()
			defer mu.Unlock()
			if err != nil {
				errs = append(errs, err)
				return
			}
			hashes[f] = sha256Hex(body)
		})
	}
	wg.Wait()
	if len(errs) > 0 {
		return nil, errs[0]
	}
	return hashes, nil
}

func fetch(url string) ([]byte, error) {
	resp, err := http.Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("%s: %s", url, resp.Status)
	}
	return io.ReadAll(resp.Body)
}

func render(name, module, path, zipHash string, files []file, hashes map[file]string) []byte {
	if path == "" {
		path = "FILE"
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, `# SPDX-FileCopyrightText: © 2026 Austin Seipp
# SPDX-License-Identifier: Apache-2.0

# @`+`generated by lock.go; do not edit. Regenerate after changing the version
# in BUILD with:
#
#   buck2 run toolchains//golang/lsp:lock -- -w %[1]s

# The module proxy files the module below builds from, by sha256: its own
# module zip, then each go.mod and module zip its go.sum lists.
%[3]s = {
    "module": %[2]q,
    "zip": %[4]q,
    "deps": {
`, path, module, name, zipHash)
	for _, f := range files {
		fmt.Fprintf(&b, "        (%q, %q, %q): %q,\n", f.path, f.version, f.ext, hashes[f])
	}
	b.WriteString("    },\n}\n")
	return b.Bytes()
}

// escape applies the module proxy's case encoding: each upper-case letter
// becomes '!' and its lower-case form, so paths stay distinct on
// case-insensitive file systems.
func escape(s string) string {
	var b strings.Builder
	for _, r := range s {
		if 'A' <= r && r <= 'Z' {
			b.WriteByte('!')
			r += 'a' - 'A'
		}
		b.WriteRune(r)
	}
	return b.String()
}

func sha256Hex(body []byte) string {
	sum := sha256.Sum256(body)
	return hex.EncodeToString(sum[:])
}

func fatalf(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "lock: "+format+"\n", args...)
	os.Exit(1)
}
